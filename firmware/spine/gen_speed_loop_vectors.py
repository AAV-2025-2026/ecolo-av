#!/usr/bin/env python3
"""
Regenerate the speed loop's shared examples from Gazebo's port of it.

Writes firmware/spine/speed_loop_vectors.txt, which both copies of the speed loop check:

  firmware/spine/crates/spine-core/tests/speed_loop_vectors.rs   (the spine's Rust)
  src/backends/aav_gazebo/test/test_actuator_model.py            (Gazebo's Python port)

Each case runs one profile ('default', 'smooth') from a fresh loop through a list of ticks.
Run it after any change to either copy's update, then `tools/test.sh`:

  python3 firmware/spine/gen_speed_loop_vectors.py
"""

import importlib.util
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
PORT = ROOT / 'src/backends/aav_gazebo/aav_gazebo/actuator_model.py'
OUT = ROOT / 'firmware/spine/speed_loop_vectors.txt'

spec = importlib.util.spec_from_file_location('actuator_model', PORT)
port = importlib.util.module_from_spec(spec)
sys.modules['actuator_model'] = port  # dataclasses look the module up while loading
spec.loader.exec_module(port)

DT = 0.01

HEADER = """\
# The spine's speed loop: examples both copies must agree on (TODO 27).
#
# Generated by firmware/spine/gen_speed_loop_vectors.py from Gazebo's port. Do not edit.
#
# Checked by:
#   firmware/spine/crates/spine-core/tests/speed_loop_vectors.rs   (the spine's Rust, f32)
#   src/backends/aav_gazebo/test/test_actuator_model.py            (Gazebo's port, Python)
#
# 'case <name> <profile>' starts a fresh loop with that profile. Each line after it is a
# tick: target and measured speed (m/s) and dt (s) in; throttle, brake (0..1) and the
# gear (1 reverse) out.
#
# target      measured    dt      throttle    brake       reverse
"""


def ramp_and_follow():
    """Speed up to 1 m/s with ego's ramp, the car lagging behind, then hold."""
    ticks = []
    v = 0.0
    for k in range(80):
        target = min(1.0, 0.02 * k)
        v += (target - v) * 0.04 + (0.008 if 50 < k < 70 else 0.0)
        ticks.append((target, v))
    return ticks


def held_back():
    """Ask for 3 m/s while the car can't move (pinned at full throttle), then let go."""
    return [(3.0, 0.0)] * 40 + [(3.0, 2.0 + 0.03 * k) for k in range(30)]


def overspeed_and_coast():
    """1 m/s asked: inside the coast band, then past it (the brake), then back under."""
    return [(1.0, 0.5)] * 15 + [(1.0, 1.1)] * 5 + [(1.0, 1.5)] * 5 + [(1.0, 0.9)] * 15


def stop_then_reverse():
    """A stop from 0.5 m/s, then reverse at 0.5 (the gear changes only when stopped)."""
    ticks = [(0.0, 0.5 - 0.02 * k) for k in range(30)]
    ticks += [(-0.5, 0.2)] * 5 + [(-0.5, 0.0)] * 5
    ticks += [(-0.5, -0.02 * k) for k in range(30)]
    return ticks


CASES = {
    'ramp': ramp_and_follow,
    'held-back': held_back,
    'coast-brake': overspeed_and_coast,
    'stop-reverse': stop_then_reverse,
}


def lines():
    """Return the file's example lines (no header)."""
    out = []
    for profile in port.SPEED_LOOP_PROFILES:
        for name, build in CASES.items():
            out.append(f'case {name} {profile}')
            loop = port.SpeedLoop(port.speed_loop_profile(profile))
            for target, measured in build():
                target, measured = round(target, 6), round(measured, 6)
                d = loop.update(target, measured, DT)
                out.append(f'{target:<11.6f} {measured:<11.6f} {DT:<7g} {d.throttle:<11.7f} '
                           f'{d.brake:<11.7f} {int(d.reverse)}'.rstrip())
    return out


def text():
    """Return the whole file."""
    return HEADER + '\n'.join(lines()) + '\n'


if __name__ == '__main__':
    OUT.write_text(text())
    print(f'wrote {OUT.relative_to(ROOT)}')
