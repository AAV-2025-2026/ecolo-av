#!/usr/bin/env python3
"""
Regenerate the car model's shared test vectors, from the Python model.

The states come from ros/bringup/aav_description/aav_description/car_model.py (step and
predict). The Rust twin (this crate, car-model) must give the same states:

  - pedal cases: exactly (1e-9), as both do the same f64 sums;
  - speed cases: within 1e-3, as the Rust runs spine-core's own speed loop (f32), the one
    the Python SpeedLoop is a port of (firmware/spine/speed_loop_vectors.txt checks those).

Writes:
  ros/bringup/aav_description/car-model/vectors.json
    read by tests/vectors.rs (`cargo test`) and aav_description's test_car_model.py

Run it after any change to car_model.py or the crate:
  python3 ros/bringup/aav_description/car-model/gen_vectors.py
"""

from dataclasses import asdict
import importlib.util
import json
import math
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
MODEL = HERE.parent / 'aav_description' / 'car_model.py'
OUT = HERE / 'vectors.json'
FIELDS = ('x', 'y', 'yaw', 'v', 'steer', 'throttle_level', 'brake_level')

spec = importlib.util.spec_from_file_location('car_model', MODEL)
cm = importlib.util.module_from_spec(spec)
sys.modules['car_model'] = cm  # dataclasses look the module up while loading
spec.loader.exec_module(cm)

LAGGY = cm.ActuatorConfig(throttle_dead_time=0.06, brake_dead_time=0.04,
                          steer_dead_time=0.1, steer_offset=0.01, throttle_deadband=0.05)


def pedals(throttle=0.0, brake=0.0, steer=0.0, reverse=False):
    return {'throttle': throttle, 'brake': brake, 'reverse': reverse, 'steer': steer}


def speed(v, steer=0.0):
    return {'speed': v, 'steer': steer}


def command(c):
    if 'speed' in c:
        return cm.Command(steer=c['steer'], speed=c['speed'])
    return cm.Command(steer=c['steer'], throttle=c['throttle'], brake=c['brake'],
                      reverse=c['reverse'])


def segments(*parts):
    """dt, then (seconds, command dict)s -> dt, [[steps, command dict], ...]."""
    dt = parts[0]
    return dt, [[math.floor(seconds / dt + 0.5), c] for seconds, c in parts[1:]]


STRIDE = 5   # the vectors keep every 5th state (and the last), to stay small


CASES = [
    # name, config, profile (None: pedals), (dt, commands)
    ('full_throttle_then_brake', cm.ActuatorConfig(), None,
     segments(0.02, (2.0, pedals(1.0)), (1.0, pedals(brake=1.0)))),
    ('circle_at_full_lock', cm.ActuatorConfig(), None,
     segments(0.02, (4.0, pedals(0.6, steer=0.5)))),
    ('steer_inside_the_deadband', cm.ActuatorConfig(), None,
     segments(0.02, (0.5, pedals(0.3, steer=0.004)), (0.5, pedals(0.3, steer=-0.2)))),
    ('dead_times_and_offset', LAGGY, None,
     segments(0.02, (1.0, pedals(0.8, steer=0.3)), (0.6, pedals(brake=0.5, steer=-0.3)),
              (0.4, pedals(0.04)))),
    ('reverse', LAGGY, None,
     segments(0.01, (1.5, pedals(0.5, steer=-0.25, reverse=True)), (1.0, pedals(brake=0.4)))),
    ('dead_time_at_a_coarse_dt', LAGGY, None,
     segments(0.05, (1.0, pedals(1.0, steer=0.4)), (1.0, pedals(steer=0.0)))),
    ('speed_loop_default', cm.ActuatorConfig(), 'default',
     segments(0.02, (4.0, speed(1.5, 0.2)), (2.0, speed(0.0)))),
    ('speed_loop_smooth_reverse', LAGGY, 'smooth',
     segments(0.02, (2.0, speed(1.0)), (3.0, speed(-0.5, -0.1)))),
    ('speed_loop_lqi', LAGGY, 'lqi',
     segments(0.02, (3.0, speed(2.0, 0.1)), (2.0, speed(0.5)))),
    # A person aboard: the same pedals push and stop the heavier car less (share).
    ('loaded_throttle_then_brake', cm.ActuatorConfig(payload=90.0), None,
     segments(0.02, (2.0, pedals(1.0)), (1.0, pedals(brake=1.0)))),
    ('loaded_speed_loop_stop', cm.ActuatorConfig(mass=150.0, payload=120.0), 'default',
     segments(0.02, (4.0, speed(1.5)), (3.0, speed(0.0)))),
]


def run(cfg, profile, dt, commands):
    loop = cm.SpeedLoop(cm.speed_loop_profile(profile)) if profile else None
    state = cm.CarState()
    every = [command(c) for steps, c in commands for _ in range(steps)]
    states = []
    for i, c in enumerate(every, 1):
        state = cm.step(cfg, state, c, dt, loop)
        if i % STRIDE == 0 or i == len(every):
            states.append([i] + [getattr(state, f) for f in FIELDS])
    return states


def main():
    cases = []
    for name, cfg, profile, (dt, commands) in CASES:
        cases.append({'name': name, 'config': asdict(cfg), 'speed_loop': profile, 'dt': dt,
                      'commands': commands, 'states': run(cfg, profile, dt, commands)})
    # predict: from a moving, turning state, 2 s ahead, one held command (ego's trace).
    start = cm.step(LAGGY, cm.CarState(v=1.2, yaw=0.3), cm.Command(steer=0.2, throttle=0.4),
                    0.02)
    trace = cm.predict(LAGGY, start, cm.Command(steer=0.2, speed=1.0), 0.02, 2.0,
                       cm.SpeedLoop(cm.speed_loop_profile('default')))
    doc = {
        'note': 'Generated by gen_vectors.py from car_model.py. Do not edit. commands: [steps, '
                'command]. states: [step number, the fields in order], every 5th step '
                'and the last. Pedal cases match exactly (1e-9); speed '
                'cases within 1e-3 (spine-core speed loop, f32).',
        'fields': list(FIELDS), 'stride': STRIDE,
        'cases': cases,
        'predict': {
            'config': asdict(LAGGY), 'speed_loop': 'default', 'dt': 0.02, 'horizon': 2.0,
            'start': {**{f: getattr(start, f) for f in FIELDS},
                      'steer_motor': start.steer_motor,
                      'steer_setpoint': start.steer_setpoint,
                      'steer_linkage': start.steer_linkage,
                      'throttle_delay': list(start.throttle_delay),
                      'brake_delay': list(start.brake_delay),
                      'steer_delay': list(start.steer_delay)},
            'command': speed(1.0, 0.2),
            'states': [[getattr(s, f) for f in FIELDS] for s in trace],
        },
    }
    OUT.write_text(json.dumps(doc, separators=(',', ':')) + '\n')
    print(f'wrote {OUT.relative_to(HERE.parents[3])}')


if __name__ == '__main__':
    main()
